  function t(lang, key) {
    return (dict[lang] && dict[lang][key]) || dict.en[key] || '';
  }

  function apply(lang) {
    if (!dict[lang]) lang = 'en';
    document.documentElement.lang = lang === 'en' ? 'en' : lang;
    document.body.dataset.lang = lang;
    localStorage.setItem(STORAGE_KEY, lang);

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const value = t(lang, el.getAttribute('data-i18n'));
      if (!value) return;
      if (el.hasAttribute('data-i18n-html')) el.innerHTML = value.replaceAll('\n', '<br>');
      else el.textContent = value;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const value = t(lang, el.getAttribute('data-i18n-placeholder'));
      if (value) el.setAttribute('placeholder', value);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      const value = t(lang, el.getAttribute('data-i18n-aria'));
      if (value) el.setAttribute('aria-label', value);
    });

    document.querySelectorAll('a, button, label, h1, h2, h3, h4, h5, h6, span, p, th, td, option').forEach((el) => {
      if (el.closest('script, style, code, pre')) return;
      if (el.hasAttribute('data-i18n') || el.children.length) return;
      const text = el.textContent.trim();
      if (phrases[text] && !el.hasAttribute('data-i18n-phrase')) {
        el.setAttribute('data-i18n-phrase', text);
      }
    });
    document.querySelectorAll('[data-i18n-phrase]').forEach((el) => {
      const source = el.getAttribute('data-i18n-phrase');
      const key = phrases[source];
      const value = key ? t(lang, key) : '';
      if (value) el.textContent = value;
    });

    document.querySelectorAll('[data-lang]').forEach((btn) => {
      btn.classList.toggle('is-active', btn.getAttribute('data-lang') === lang);
    });
  }

  window.NexusI18n = {
    apply,
    current: () => localStorage.getItem(STORAGE_KEY) || 'en',
  };

  document.addEventListener('DOMContentLoaded', () => {
    apply(localStorage.getItem(STORAGE_KEY) || 'en');
    document.querySelectorAll('[data-lang]').forEach((btn) => {
      btn.addEventListener('click', () => apply(btn.getAttribute('data-lang')));
    });
  });
